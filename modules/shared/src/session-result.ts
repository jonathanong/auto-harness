import type { SessionStatus } from "./types.ts";

/** Machine-readable outcome captured at the end of a session attempt. */
export type SessionResult = {
  summary: string;
  summarySource: "agent" | "harness";
  summaryTruncated?: true;
  branch?: string;
  filesChanged?: string[];
  filesChangedTruncated?: true;
  pullRequestUrl?: string;
};

/** Bounded harness fallback when a terminal path cannot collect a checkout result. */
export function harnessSessionResult(
  status: Extract<SessionStatus, "completed" | "failed" | "cancelled" | "timed_out">,
): SessionResult {
  return { summary: `Session ${status}`, summarySource: "harness" };
}

export const SESSION_RESULT_PROTOCOL_VERSION = 3;
export const MAX_SESSION_RESULT_BYTES = 32 * 1024;
export const MAX_SESSION_RESULT_SUMMARY_BYTES = 4 * 1024;
export const MAX_SESSION_RESULT_BRANCH_BYTES = 1024;
export const MAX_SESSION_RESULT_URL_BYTES = 2 * 1024;
export const MAX_SESSION_RESULT_FILES = 256;
export const MAX_SESSION_RESULT_FILE_BYTES = 4 * 1024;

function bytes(value: string): number {
  return new TextEncoder().encode(value).byteLength;
}

function truncate(value: string, maxBytes: number): string {
  if (bytes(value) <= maxBytes) return value;
  let end = Math.min(value.length, maxBytes);
  while (end > 0 && bytes(value.slice(0, end)) > maxBytes) end -= 1;
  return value.slice(0, end);
}

function text(value: unknown, maxBytes: number): string | undefined {
  return typeof value === "string" ? truncate(value, maxBytes) : undefined;
}

function validHttpUrl(value: string): boolean {
  try {
    const url = new URL(value);
    return url.protocol === "http:" || url.protocol === "https:";
  } catch {
    return false;
  }
}

/** Return a bounded, canonical result, or undefined for an invalid envelope. */
export function normalizeSessionResult(value: unknown): SessionResult | undefined {
  if (!value || typeof value !== "object" || Array.isArray(value)) return undefined;
  const input = value as Record<string, unknown>;
  if (input.summarySource !== "agent" && input.summarySource !== "harness") return undefined;
  const summary = text(input.summary, MAX_SESSION_RESULT_SUMMARY_BYTES);
  if (summary === undefined || summary.length === 0) return undefined;
  const result: SessionResult = { summary, summarySource: input.summarySource };
  if (
    bytes(input.summary as string) > MAX_SESSION_RESULT_SUMMARY_BYTES ||
    input.summaryTruncated === true
  ) {
    result.summaryTruncated = true;
  }
  // Branch names are identifiers. Unlike summaries, they must never be
  // truncated into a different identifier; an oversized name is unavailable.
  if (
    typeof input.branch === "string" &&
    input.branch.length > 0 &&
    bytes(input.branch) <= MAX_SESSION_RESULT_BRANCH_BYTES
  ) {
    result.branch = input.branch;
  }
  if (
    typeof input.pullRequestUrl === "string" &&
    bytes(input.pullRequestUrl) <= MAX_SESSION_RESULT_URL_BYTES &&
    validHttpUrl(input.pullRequestUrl)
  ) {
    result.pullRequestUrl = input.pullRequestUrl;
  }
  if (Array.isArray(input.filesChanged)) {
    const files = new Set<string>();
    for (const candidate of input.filesChanged) {
      if (typeof candidate !== "string" || candidate.length === 0) continue;
      if (bytes(candidate) > MAX_SESSION_RESULT_FILE_BYTES) {
        result.filesChangedTruncated = true;
        continue;
      }
      files.add(candidate);
      if (files.size >= MAX_SESSION_RESULT_FILES) break;
    }
    if (files.size > 0 || input.filesChanged.length === 0)
      result.filesChanged = [...files].toSorted();
    if (
      input.filesChanged.length > MAX_SESSION_RESULT_FILES ||
      input.filesChangedTruncated === true
    )
      result.filesChangedTruncated = true;
  }
  // A result generated by an untrusted peer is never allowed to exceed the
  // storage/wire budget. Drop optional fields in deterministic order if needed.
  while (bytes(JSON.stringify(result)) > MAX_SESSION_RESULT_BYTES && result.filesChanged?.length) {
    result.filesChanged = result.filesChanged.slice(0, -1);
    result.filesChangedTruncated = true;
  }
  return result;
}

export function isSessionResult(value: unknown): value is SessionResult {
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  const input = value as Record<string, unknown>;
  if (
    typeof input.summary !== "string" ||
    input.summary.length === 0 ||
    bytes(input.summary) > MAX_SESSION_RESULT_SUMMARY_BYTES
  ) {
    return false;
  }
  if (input.summarySource !== "agent" && input.summarySource !== "harness") return false;
  if (input.summaryTruncated !== undefined && input.summaryTruncated !== true) return false;
  if (
    input.branch !== undefined &&
    (typeof input.branch !== "string" || bytes(input.branch) > MAX_SESSION_RESULT_BRANCH_BYTES)
  ) {
    return false;
  }
  if (
    input.pullRequestUrl !== undefined &&
    (typeof input.pullRequestUrl !== "string" ||
      bytes(input.pullRequestUrl) > MAX_SESSION_RESULT_URL_BYTES ||
      !validHttpUrl(input.pullRequestUrl))
  ) {
    return false;
  }
  if (input.filesChanged !== undefined) {
    if (
      !Array.isArray(input.filesChanged) ||
      input.filesChanged.length > MAX_SESSION_RESULT_FILES ||
      input.filesChanged.some(
        (file) =>
          typeof file !== "string" ||
          file.length === 0 ||
          bytes(file) > MAX_SESSION_RESULT_FILE_BYTES,
      )
    ) {
      return false;
    }
  }
  return input.filesChangedTruncated === undefined || input.filesChangedTruncated === true;
}
